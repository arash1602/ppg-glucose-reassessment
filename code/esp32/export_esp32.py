"""Export a trained TinyCNN checkpoint + the PPG preprocessing constants to C headers.

  python esp32/export_esp32.py --ckpt C:\\glucose_data\\models\\tiny_beat_all_fold0.pt
         [--raw C:\\glucose_data\\vitaldb_raw\\123.npz]   (real test window; default: synthetic)

Writes into esp32/firmware/include/:
  glucose_model.h   fused (BatchNorm folded into conv) weights, float32 + per-channel int8
  dsp_coeffs.h      Butterworth band-pass SOS + initial-condition coefficients (from scipy)
  test_window.h     one 60-s PPG window (100 Hz) + the Python reference results for it
and esp32/pc_test/reference.json (same reference, for the PC comparison test).
"""
import argparse
import json
import sys
from pathlib import Path

import numpy as np
import torch
from scipy.signal import sosfilt_zi

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import config as C          # noqa: E402
import models               # noqa: E402
import ppg                  # noqa: E402

INC = HERE / "firmware" / "include"
WIN_S = 60                                  # seconds of PPG analysed per glucose estimate on the device


def fold_bn(conv, bn):
    w = conv.weight.detach().double()
    s = bn.weight.detach().double() / torch.sqrt(bn.running_var.double() + bn.eps)
    wf = w * s[:, None, None]
    bf = bn.bias.detach().double() - bn.running_mean.double() * s
    return wf.numpy(), bf.numpy()


def cnum(v, digits, suffix):
    s = f"{float(v):.{digits}g}"
    if "." not in s and "e" not in s and "n" not in s:   # 2564 -> 2564.0 (2564f is not valid C)
        s += ".0"
    return s + suffix


def carr(name, a, ctype="float", fmt=None):
    a = np.asarray(a).ravel()
    if ctype == "float":
        body = ",".join(cnum(v, 9, "f") for v in a)
    elif ctype == "double":
        body = ",".join(cnum(v, 17, "") for v in a)
    else:
        body = ",".join(str(int(v)) for v in a)
    return f"static const {ctype} {name}[{len(a)}] = {{{body}}};\n"


def quant_per_channel(w):
    """symmetric int8 per output channel: w ~= q * scale[c]"""
    flat = w.reshape(w.shape[0], -1)
    scale = np.abs(flat).max(1) / 127.0
    scale[scale == 0] = 1.0
    q = np.clip(np.round(flat / scale[:, None]), -127, 127).astype(np.int8)
    return q.reshape(w.shape), scale


def python_reference(net, x_raw, mu, sd):
    """exact Python pipeline that the C code must reproduce"""
    xf = ppg.bandpass(x_raw.astype(np.float64))
    B, P, q = ppg.extract_beats(xf)
    with torch.no_grad():
        pb = net(torch.from_numpy(B.astype(np.float64)).unsqueeze(1)).squeeze(1).double().numpy() * sd + mu if len(B) else np.array([])
    ok = len(B) >= 3                     # same rule as the C code: < 3 beats -> no estimate
    return {"n_peaks": q["n_peaks"], "n_windows": q["n_windows"], "n_beats": int(len(B)),
            "peaks": [int(p) for p in P] if len(B) else [], "beat_preds": pb.tolist(),
            "glucose_median": float(np.median(pb)) if ok else -1.0,
            "filtered_first10": xf[:10].tolist(), "beat0": B[0].tolist() if len(B) else []}


def synthetic_window(seed=3):
    rng = np.random.default_rng(seed)
    t = np.arange(WIN_S * C.FS) / C.FS
    hr = 72 + 3 * np.sin(2 * np.pi * 0.05 * t)
    phase = np.cumsum(hr / 60 / C.FS) % 1
    beat = np.exp(-((phase - 0.25) / 0.07) ** 2) + 0.4 * np.exp(-((phase - 0.55) / 0.1) ** 2)
    return (1000 * beat + 60 * np.sin(2 * np.pi * 0.25 * t) + rng.normal(0, 12, len(t)) + 2000).astype(np.float32)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ckpt", required=True)
    ap.add_argument("--raw", default="", help="VitalDB raw case .npz (from step 1) for a real test window")
    ap.add_argument("--reading", type=int, default=0)
    args = ap.parse_args()

    ck = torch.load(args.ckpt, map_location="cpu")
    if ck["args"]["model"] != "tiny" or ck["args"].get("demo"):
        raise SystemExit("export supports the TinyCNN without --demo")
    net = models.build("tiny")
    net.load_state_dict(ck["state"]); net.eval().double()
    mu, sd = float(ck["mu"]), float(ck["sd"])

    INC.mkdir(parents=True, exist_ok=True)
    feats = list(net.features)
    convs = [(feats[i], feats[i + 1]) for i in range(0, len(feats), 3)]
    lin = [m for m in net.head.mlp if isinstance(m, torch.nn.Linear)]

    h = ["// Auto-generated by export_esp32.py - do not edit\n#pragma once\n#include <stdint.h>\n\n",
         f"// source checkpoint: {Path(args.ckpt).name}\n",
         f"#define GM_N_CONV {len(convs)}\n#define GM_IN_LEN {C.BEAT_LEN}\n",
         f"#define GM_FC1_OUT {lin[0].out_features}\n",
         f"static const float GM_MU = {mu:.9g}f;\nstatic const float GM_SD = {sd:.9g}f;\n"]
    shapes = []
    for i, (conv, bn) in enumerate(convs):
        w, b = fold_bn(conv, bn)
        q, sc = quant_per_channel(w)
        co, ci, k = w.shape
        shapes.append((ci, co, k, conv.stride[0], conv.padding[0]))
        h += [carr(f"GM_C{i}_W", w), carr(f"GM_C{i}_B", b),
              carr(f"GM_C{i}_WQ", q, "int8_t"), carr(f"GM_C{i}_WS", sc)]
    for j, l in enumerate(lin):
        w = l.weight.detach().double().numpy(); b = l.bias.detach().double().numpy()
        q, sc = quant_per_channel(w[:, :, None])
        h += [carr(f"GM_FC{j}_W", w), carr(f"GM_FC{j}_B", b), carr(f"GM_FC{j}_WQ", q, "int8_t"), carr(f"GM_FC{j}_WS", sc)]
    h.append("// per conv layer: in_ch, out_ch, kernel, stride, pad\n")
    h.append("static const int GM_SHAPES[GM_N_CONV][5] = {" + ",".join("{%d,%d,%d,%d,%d}" % s for s in shapes) + "};\n")
    h.append("static const float* const GM_CW[GM_N_CONV] = {" + ",".join(f"GM_C{i}_W" for i in range(len(convs))) + "};\n")
    h.append("static const float* const GM_CB[GM_N_CONV] = {" + ",".join(f"GM_C{i}_B" for i in range(len(convs))) + "};\n")
    h.append("static const int8_t* const GM_CWQ[GM_N_CONV] = {" + ",".join(f"GM_C{i}_WQ" for i in range(len(convs))) + "};\n")
    h.append("static const float* const GM_CWS[GM_N_CONV] = {" + ",".join(f"GM_C{i}_WS" for i in range(len(convs))) + "};\n")
    (INC / "glucose_model.h").write_text("".join(h))

    sos = ppg._SOS
    zi = sosfilt_zi(sos)
    d = ["// Auto-generated by export_esp32.py\n#pragma once\n",
         f"#define DSP_FS {C.FS}\n#define DSP_N_SOS {len(sos)}\n#define DSP_BEAT_LEN {C.BEAT_LEN}\n",
         f"#define DSP_PEAK_DIST {int(0.4 * C.FS)}\n#define DSP_PEAK_PROM 0.8\n#define DSP_COS_MIN {C.COS_SIM_MIN}\n",
         carr("DSP_SOS", sos, "double"),
         carr("DSP_ZI", zi, "double")]
    (INC / "dsp_coeffs.h").write_text("".join(d))

    if args.raw:
        z = np.load(args.raw)
        x = z["ppg"][args.reading]
        start = len(x) // 2 - WIN_S * C.FS // 2          # centred on the glucose reading
        x = x[start:start + WIN_S * C.FS]
        label = float(z["glucose"][args.reading]); src = f"{Path(args.raw).name} reading {args.reading}"
    else:
        x, label, src = synthetic_window(), float("nan"), "synthetic"
    ref = python_reference(net, x, mu, sd)
    ref.update({"source": src, "label_mg_dl": label, "mu": mu, "sd": sd})
    t = ["// Auto-generated by export_esp32.py\n#pragma once\n",
         f"// {src}\n#define TW_LEN {len(x)}\n",
         f"static const float TW_LABEL_MGDL = {label if np.isfinite(label) else -1:.3f}f;\n",
         f"static const float TW_REF_GLUCOSE = {ref['glucose_median'] or -1:.6f}f;\n",
         f"static const int TW_REF_NBEATS = {ref['n_beats']};\n",
         carr("TW_PPG", x, "float")]
    (INC / "test_window.h").write_text("".join(t))
    (HERE / "pc_test").mkdir(exist_ok=True)
    np.savetxt(HERE / "pc_test" / "test_window.txt", x)
    (HERE / "pc_test" / "reference.json").write_text(json.dumps(ref))

    nparam = sum(p.numel() for p in net.parameters())
    print(f"exported {Path(args.ckpt).name}: {nparam} params | float32 {nparam*4/1024:.1f} kB | int8 {nparam/1024:.1f} kB")
    print(f"test window ({src}): {ref['n_beats']} beats, Python glucose {ref['glucose_median']}")


if __name__ == "__main__":
    main()
