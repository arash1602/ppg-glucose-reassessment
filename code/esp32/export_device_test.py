"""Write firmware/include/dev_test.h: the self-test vectors for the device model.

Uses pc_test/device_reference_avg.json (14_device_avg.py, K one-minute windows per estimate) when it
exists and matches the K in device_model.h, otherwise pc_test/device_reference.json (13_device_train.py,
one window). One calibration-free sequence and one calibrated pair, with the Python results."""
import json, re
from pathlib import Path
import numpy as np
H = Path(__file__).resolve().parent
hdr = (H / "firmware" / "include" / "device_model.h").read_text()
m = re.search(r"#define DEV_AVG_WINDOWS (\d+)", hdr)
K = int(m.group(1)) if m else 1
avg = H / "pc_test" / "device_reference_avg.json"
if "14_device_avg.py" in hdr.splitlines()[0]:          # models exported by 14_device_avg.py (any K)
    R = json.loads(avg.read_text())
    assert R["K"] == K, f"device_model.h has K={K} but {avg.name} has K={R['K']}: rerun 14_device_avg.py"
    ref = R["cases"]
    free = next(r for r in ref if "cal_windows" not in r)
    cal = next(r for r in ref if "cal_windows" in r)
    fw, c0, c1 = free["windows"], cal["cal_windows"], cal["windows"]
else:
    ref = json.loads((H / "pc_test" / "device_reference.json").read_text())
    free = next(r for r in ref if "x_cal" not in r)
    cal = next(r for r in ref if "x_cal" in r)
    fw, c0, c1 = [free["x"]], [cal["x_cal"]], [cal["x"]]
num = lambda v: "NAN" if v is None or not np.isfinite(v) else (lambda s: s if ("." in s or "e" in s) else s + ".0")(repr(float(v)))
def arr2(name, W):
    L = max(len(w) for w in W)
    rows = ["{" + ",".join(num(np.float32(v)) + "f" for v in w) + "}" for w in W]
    return f"static const float {name}[{len(W)}][{L}] = {{" + ",\n".join(rows) + "};\n"
darr = lambda name, a: f"static const double {name}[{len(a)}] = {{" + ",".join(num(v) for v in a) + "};\n"
s = ["// Auto-generated by export_device_test.py\n#pragma once\n#include <math.h>\n",
     f"#define DT_K {K}\n#define DT_LEN {len(fw[0])}\n",
     f"#define DT_FREE_NW {len(fw)}\n#define DT_CAL0_NW {len(c0)}\n#define DT_CAL1_NW {len(c1)}\n",
     arr2("DT_FREE_PPG", fw), darr("DT_FREE_PROFILE", free["profile"]),
     f"static const double DT_FREE_REF = {free['pred_free']!r};\nstatic const double DT_FREE_LABEL = {free['label']!r};\n",
     arr2("DT_CAL0_PPG", c0), arr2("DT_CAL1_PPG", c1), darr("DT_CAL_PROFILE", cal["profile"]),
     f"static const double DT_CAL_GLUCOSE = {cal['cal_glucose']!r};\nstatic const double DT_CAL_MINUTES = {cal['minutes_since_cal']!r};\n",
     f"static const double DT_CAL_REF = {cal['pred_cal']!r};\nstatic const double DT_CAL_LABEL = {cal['label']!r};\n"]
(H / "firmware" / "include" / "dev_test.h").write_text("".join(s))
print(f"dev_test.h (K={K}): free sequence of {len(fw)} window(s) (Python {free['pred_free']:.3f}, lab {free['label']:.0f}); "
      f"calibration pair (Python {cal['pred_cal']:.3f}, lab {cal['label']:.0f}, {cal['minutes_since_cal']:.0f} min after a {cal['cal_glucose']:.0f} mg/dL fingerstick)")
